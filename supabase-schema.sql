create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to anon, authenticated;

create or replace function public.can_use_support_chat()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    exists (
      select 1 from public.profiles
      where id = (select auth.uid()) and role = 'admin'
    )
    or exists (
      select 1 from public.orders
      where user_id = (select auth.uid())
    );
$$;

revoke all on function public.can_use_support_chat() from public;
grant execute on function public.can_use_support_chat() to authenticated;

create or replace function public.touch_support_session()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.support_sessions
  set updated_at = now()
  where id = new.session_id;
  return new;
end;
$$;

drop trigger if exists on_support_message_created on public.support_messages;
create trigger on_support_message_created
after insert on public.support_messages
for each row execute procedure public.touch_support_session();

create or replace function public.handle_new_store_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  invited boolean;
begin
  select exists (
    select 1 from public.admin_invites
    where email = lower(new.email) and accepted_at is null
  ) into invited;

  insert into public.profiles (id, name, email, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    lower(coalesce(new.email, '')),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    case when invited then 'admin' else 'customer' end
  )
  on conflict (id) do nothing;

  if invited then
    update public.admin_invites
    set accepted_at = now()
    where email = lower(new.email) and accepted_at is null;
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_store_profile on auth.users;
create trigger on_auth_user_created_store_profile
after insert on auth.users
for each row execute procedure public.handle_new_store_user();

create or replace function public.set_order_snapshot()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  item record;
  product record;
  quantity integer;
  expected_total numeric(10, 2) := 0;
  normalized_items jsonb := '[]'::jsonb;
begin
  if jsonb_typeof(new.items) <> 'array' or jsonb_array_length(new.items) = 0 then
    raise exception 'An order must contain at least one product';
  end if;

  for item in select value from jsonb_array_elements(new.items) as entry(value) loop
    if coalesce(item.value ->> 'qty', '') !~ '^[1-9][0-9]*$' then
      raise exception 'The order contains an invalid quantity';
    end if;
    quantity := (item.value ->> 'qty')::integer;
    if quantity > 99 then
      raise exception 'Order quantities cannot exceed 99';
    end if;

    select p.id, p.name_en, p.name_ar, p.price
    into product
    from public.products p
    where p.id = (item.value ->> 'id')::bigint;
    if not found then
      raise exception 'The order contains an unknown product';
    end if;

    expected_total := expected_total + product.price * quantity;
    normalized_items := normalized_items || jsonb_build_array(jsonb_build_object(
      'id', product.id,
      'en', product.name_en,
      'ar', product.name_ar,
      'price', product.price,
      'qty', quantity
    ));
  end loop;

  if trim(new.customer_name) = '' or trim(new.phone) = '' or trim(new.address) = '' then
    raise exception 'Customer name, phone, and address are required';
  end if;

  new.total := expected_total;
  new.items := normalized_items;
  new.email := lower(trim(new.email));
  return new;
end;
$$;

